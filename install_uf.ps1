#Requires -RunAsAdministrator
<#
.SYNOPSIS
  Install the Splunk Universal Forwarder on Windows and point it at your indexer.

.EXAMPLE
  .\install_uf.ps1 -ServerIP 192.168.1.50
  Downloads Universal Forwarder 10.6.1.1 (64-bit) and points it at 192.168.1.50:9997.

.EXAMPLE
  .\install_uf.ps1 -ServerIP 192.168.1.50 -Port 9997 -MsiPath .\splunkforwarder.msi -Index windows

.NOTES
  For another version: splunk.com -> Universal Forwarder -> Windows 64-bit .msi
  -> "Copy wget link", then pass it with -MsiUrl.
#>
param(
    [Parameter(Mandatory = $true)][string]$ServerIP,
    [ValidateRange(1, 65535)][int]$Port = 9997,
    [string]$MsiUrl = "https://download.splunk.com/products/universalforwarder/releases/10.6.1.1/windows/splunkforwarder-10.6.1.1-b2ae2962645c-windows-x64.msi",
    [string]$MsiPath,
    [string]$AdminUser = "admin",
    [SecureString]$AdminPassword,
    [string]$Index = "main",
    [string]$InstallDir = "C:\Program Files\SplunkUniversalForwarder"
)

$ErrorActionPreference = "Stop"
function Info($m) { Write-Host "[+] $m" -ForegroundColor Green }
function Warn($m) { Write-Host "[!] $m" -ForegroundColor Yellow }
function Fail($m) { Write-Host "[x] $m" -ForegroundColor Red; exit 1 }

if (Get-Service -Name SplunkForwarder -ErrorAction SilentlyContinue) {
    Fail "SplunkForwarder service already exists. Uninstall it first for a clean install."
}

if (-not $AdminPassword) {
    $AdminPassword = Read-Host "Set a forwarder admin password (min 8 chars)" -AsSecureString
}
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($AdminPassword)
$PlainPass = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
[Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
if ($PlainPass.Length -lt 8) { Fail "Password must be at least 8 characters." }

# ---------- connectivity test (warn only) ----------
Info "Testing connection to ${ServerIP}:${Port} ..."
if ((Test-NetConnection -ComputerName $ServerIP -Port $Port -WarningAction SilentlyContinue).TcpTestSucceeded) {
    Info "Port $Port on $ServerIP is reachable."
} else {
    Warn "Can't reach ${ServerIP}:${Port}. Installing anyway - check receiving is enabled and firewalls allow it."
}

# ---------- get MSI ----------
$downloaded = $null
if (-not $MsiPath) {
    $downloaded = Join-Path $env:TEMP "splunkforwarder.msi"
    Info "Downloading forwarder MSI..."
    $ProgressPreference = "SilentlyContinue"   # makes Invoke-WebRequest much faster
    Invoke-WebRequest -Uri $MsiUrl -OutFile $downloaded -UseBasicParsing
    $MsiPath = $downloaded
}
if (-not (Test-Path $MsiPath)) { Fail "MSI not found: $MsiPath" }
$MsiPath = (Resolve-Path $MsiPath).Path

# ---------- install ----------
$log = Join-Path $env:TEMP "splunkforwarder_install.log"
$msiArgs = @(
    "/i", "`"$MsiPath`"",
    "AGREETOLICENSE=Yes",
    "RECEIVING_INDEXER=`"${ServerIP}:${Port}`"",
    "SPLUNKUSERNAME=`"$AdminUser`"",
    "SPLUNKPASSWORD=`"$PlainPass`"",
    "INSTALLDIR=`"$InstallDir`"",
    "USE_LOCAL_SYSTEM=1",      # lab-friendly: ensures the Security log is readable
    "LAUNCHSPLUNK=0",          # we start it after writing inputs.conf
    "/quiet", "/L*v", "`"$log`""
)
Info "Running installer (log: $log) ..."
$p = Start-Process msiexec.exe -ArgumentList $msiArgs -Wait -PassThru
if ($p.ExitCode -notin 0, 3010) { Fail "msiexec failed with exit code $($p.ExitCode). See $log" }

# ---------- inputs ----------
$local = Join-Path $InstallDir "etc\system\local"
New-Item -ItemType Directory -Force -Path $local | Out-Null

$inputs = @"
# Generated by install_uf.ps1
[WinEventLog://Security]
disabled = 0
index = $Index

[WinEventLog://System]
disabled = 0
index = $Index

[WinEventLog://Application]
disabled = 0
index = $Index
"@

if (Get-WinEvent -ListLog "Microsoft-Windows-Sysmon/Operational" -ErrorAction SilentlyContinue) {
    Info "Sysmon detected - adding Sysmon channel"
    $inputs += @"

[WinEventLog://Microsoft-Windows-Sysmon/Operational]
disabled = 0
index = $Index
renderXml = true
"@
}
if (Get-WinEvent -ListLog "Microsoft-Windows-PowerShell/Operational" -ErrorAction SilentlyContinue) {
    $inputs += @"

[WinEventLog://Microsoft-Windows-PowerShell/Operational]
disabled = 0
index = $Index
"@
}
Set-Content -Path (Join-Path $local "inputs.conf") -Value $inputs -Encoding ASCII

# ---------- start + verify ----------
Info "Starting SplunkForwarder service"
Start-Service SplunkForwarder
Start-Sleep -Seconds 5
Info "Forward-server status:"
& (Join-Path $InstallDir "bin\splunk.exe") list forward-server -auth "${AdminUser}:${PlainPass}"

if ($downloaded) { Remove-Item $downloaded -Force -ErrorAction SilentlyContinue }
$PlainPass = $null

Write-Host @"

Done. Forwarder on $env:COMPUTERNAME -> ${ServerIP}:${Port} (index: $Index)

Verify on the Splunk server:
  index=_internal host=$env:COMPUTERNAME | head 10
  index=$Index host=$env:COMPUTERNAME | stats count by sourcetype

If the index isn't "main", make sure it exists on the server first.
Forwarder logs: $InstallDir\var\log\splunk\splunkd.log
"@
