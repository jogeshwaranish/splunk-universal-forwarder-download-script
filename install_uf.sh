#!/usr/bin/env bash
#
# install_uf.sh — Install the Splunk Universal Forwarder on Linux and point it
# at your Splunk indexer (receiving port, usually 9997).
#
# Usage:
#   sudo ./install_uf.sh -i <SERVER_IP> [-p PORT] (-u PKG_URL | -f PKG_FILE) [-a ADMIN_PASS] [-x INDEX]
#
# Examples:
#   sudo ./install_uf.sh -i 192.168.1.50 -u 'https://download.splunk.com/products/universalforwarder/releases/.../splunkforwarder-...-linux-amd64.tgz'
#   sudo ./install_uf.sh -i 192.168.1.50 -p 9997 -f ./splunkforwarder-9.x.x-linux-amd64.tgz -x linux
#
# Get the .tgz URL from splunk.com -> Universal Forwarder download -> Linux .tgz
# -> "Copy wget link". Splunk changes these URLs every release, so the script
# takes the URL as an argument instead of hardcoding a version.

set -euo pipefail

SERVER_IP=""
PORT="9997"
PKG_URL=""
PKG_FILE=""
ADMIN_USER="admin"
ADMIN_PASS="${SPLUNK_PASSWORD:-}"
INDEX="main"
INSTALL_DIR="/opt/splunkforwarder"
SPLUNK_USER="splunkfwd"
DOWNLOADED=""

info()  { echo -e "\e[32m[+]\e[0m $*"; }
warn()  { echo -e "\e[33m[!]\e[0m $*"; }
fail()  { echo -e "\e[31m[x]\e[0m $*" >&2; exit 1; }

usage() {
  sed -n '3,15p' "$0" | sed 's/^# \{0,1\}//'
  exit 1
}

cleanup() { [[ -n "$DOWNLOADED" && -f "$DOWNLOADED" ]] && rm -f "$DOWNLOADED"; }
trap cleanup EXIT

while getopts ":i:p:u:f:a:x:h" opt; do
  case "$opt" in
    i) SERVER_IP="$OPTARG" ;;
    p) PORT="$OPTARG" ;;
    u) PKG_URL="$OPTARG" ;;
    f) PKG_FILE="$OPTARG" ;;
    a) ADMIN_PASS="$OPTARG" ;;
    x) INDEX="$OPTARG" ;;
    h|*) usage ;;
  esac
done

# ---------- checks ----------
[[ $EUID -eq 0 ]] || fail "Run as root (sudo)."
[[ -n "$SERVER_IP" ]] || { warn "Missing -i <SERVER_IP>"; usage; }
[[ "$PORT" =~ ^[0-9]+$ ]] || fail "Port must be a number."
[[ -n "$PKG_URL" || -n "$PKG_FILE" ]] || { warn "Give -u <URL> or -f <FILE>"; usage; }
[[ -d "$INSTALL_DIR" ]] && fail "$INSTALL_DIR already exists. Remove it first if you want a clean reinstall."

if [[ -z "$ADMIN_PASS" ]]; then
  read -r -s -p "Set a forwarder admin password (min 8 chars): " ADMIN_PASS; echo
fi
[[ ${#ADMIN_PASS} -ge 8 ]] || fail "Password must be at least 8 characters."

# ---------- connectivity test (warn only) ----------
info "Testing connection to $SERVER_IP:$PORT ..."
if timeout 5 bash -c "</dev/tcp/$SERVER_IP/$PORT" 2>/dev/null; then
  info "Port $PORT on $SERVER_IP is reachable."
else
  warn "Can't reach $SERVER_IP:$PORT. Installing anyway — check receiving is enabled and firewalls allow it."
fi

# ---------- get package ----------
if [[ -n "$PKG_URL" ]]; then
  DOWNLOADED="$(mktemp /tmp/splunkforwarder.XXXXXX.tgz)"
  info "Downloading forwarder package..."
  if command -v curl >/dev/null; then
    curl -fL --progress-bar -o "$DOWNLOADED" "$PKG_URL" || fail "Download failed."
  elif command -v wget >/dev/null; then
    wget -q --show-progress -O "$DOWNLOADED" "$PKG_URL" || fail "Download failed."
  else
    fail "Need curl or wget to download."
  fi
  PKG_FILE="$DOWNLOADED"
fi
[[ -f "$PKG_FILE" ]] || fail "Package not found: $PKG_FILE"
tar -tzf "$PKG_FILE" >/dev/null 2>&1 || fail "$PKG_FILE is not a valid .tgz (wrong URL? got an HTML page?)."

# ---------- service user ----------
if ! id -u "$SPLUNK_USER" >/dev/null 2>&1; then
  info "Creating service user $SPLUNK_USER"
  useradd --system --no-create-home --shell "$(command -v nologin || echo /bin/false)" "$SPLUNK_USER"
fi
# Debian/Ubuntu: auth.log/syslog are readable by group 'adm'
getent group adm >/dev/null && usermod -aG adm "$SPLUNK_USER"

# ---------- install ----------
info "Extracting to $INSTALL_DIR"
tar -xzf "$PKG_FILE" -C /opt
[[ -x "$INSTALL_DIR/bin/splunk" ]] || fail "Extraction didn't produce $INSTALL_DIR/bin/splunk"

LOCAL="$INSTALL_DIR/etc/system/local"
mkdir -p "$LOCAL"

# Admin credentials (consumed and removed by Splunk on first start)
cat > "$LOCAL/user-seed.conf" <<EOF
[user_info]
USERNAME = $ADMIN_USER
PASSWORD = $ADMIN_PASS
EOF
chmod 600 "$LOCAL/user-seed.conf"

# Where to send data
cat > "$LOCAL/outputs.conf" <<EOF
[tcpout]
defaultGroup = primary_indexers

[tcpout:primary_indexers]
server = $SERVER_IP:$PORT
EOF

# What to collect — only files that exist on this distro
{
  echo "# Generated by install_uf.sh"
  add_input() {  # path sourcetype
    if [[ -f "$1" ]]; then
      printf '\n[monitor://%s]\ndisabled = 0\nindex = %s\nsourcetype = %s\n' "$1" "$INDEX" "$2"
      echo "    monitoring $1" >&2
    fi
  }
  add_input /var/log/auth.log         linux_secure   # Debian/Ubuntu
  add_input /var/log/secure           linux_secure   # RHEL family
  add_input /var/log/syslog           syslog         # Debian/Ubuntu
  add_input /var/log/messages         syslog         # RHEL family
  add_input /var/log/audit/audit.log  linux_audit    # needs auditd
} > "$LOCAL/inputs.conf"

if [[ -f /var/log/audit/audit.log ]]; then
  warn "audit.log is root-only by default; $SPLUNK_USER may not be able to read it."
  warn "To allow it: setfacl -m u:$SPLUNK_USER:r /var/log/audit/audit.log (and adjust auditd log_group)."
fi

chown -R "$SPLUNK_USER:$SPLUNK_USER" "$INSTALL_DIR"

# ---------- first start + boot-start ----------
info "First start (accepting license, seeding admin user)..."
sudo -u "$SPLUNK_USER" "$INSTALL_DIR/bin/splunk" start --accept-license --answer-yes --no-prompt
sudo -u "$SPLUNK_USER" "$INSTALL_DIR/bin/splunk" stop

if command -v systemctl >/dev/null && [[ -d /run/systemd/system ]]; then
  info "Enabling boot-start under systemd"
  "$INSTALL_DIR/bin/splunk" enable boot-start -systemd-managed 1 -user "$SPLUNK_USER" \
      --accept-license --answer-yes --no-prompt
  systemctl daemon-reload
  systemctl start SplunkForwarder
else
  info "No systemd; enabling init.d boot-start"
  "$INSTALL_DIR/bin/splunk" enable boot-start -user "$SPLUNK_USER" --accept-license --answer-yes --no-prompt
  sudo -u "$SPLUNK_USER" "$INSTALL_DIR/bin/splunk" start
fi

# ---------- verify ----------
sleep 5
info "Forward-server status:"
sudo -u "$SPLUNK_USER" "$INSTALL_DIR/bin/splunk" list forward-server -auth "$ADMIN_USER:$ADMIN_PASS" || true

cat <<EOF

Done. Forwarder on $(hostname) -> $SERVER_IP:$PORT (index: $INDEX)

Verify on the Splunk server:
  index=_internal host=$(hostname) | head 10
  index=$INDEX host=$(hostname) | stats count by sourcetype

If the index isn't "main", make sure it exists on the server first.
Forwarder logs: $INSTALL_DIR/var/log/splunk/splunkd.log
EOF
